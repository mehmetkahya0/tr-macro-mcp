"""Scripted end-to-end demos against the real stdio server and the local corpus.

Run: uv run python scripts/demo.py > docs/demos.md
Requires `tr-macro-mcp ingest` to have run. Demos 1-4 are keyless; demo 5 needs EVDS_API_KEY.
Network: demo 2 and 4 fetch TCMB FX bulletins (cached afterwards).
"""

import datetime as dt
import os
import sys
from typing import Any

import anyio
from mcp import Client, StdioServerParameters

SERVER = StdioServerParameters(
    command=sys.executable, args=["-m", "tr_macro_mcp.server"], env=dict(os.environ)
)


def cite(c: dict[str, Any]) -> str:
    where = (
        f", p. {c['page']}" + (f" (printed {c['page_label']})" if c.get("page_label") else "")
        if c.get("page")
        else ""
    )
    extra = f", bulletin {c['bulletin_no']}" if c.get("bulletin_no") else ""
    return f"{c['source']}: {c.get('title') or ''} ({c.get('doc_date') or 'n/a'}{where}{extra}) <{c['url']}>"


def strip(text: str) -> str:
    return text.split(">>>\n", 1)[-1].rsplit("\n<<<", 1)[0]


async def call(client: Client, tool: str, args: dict[str, Any]) -> dict[str, Any]:
    result = await client.call_tool(tool, args)
    if result.is_error:
        raise SystemExit(f"{tool} failed: {result.content[0].text}")
    return result.structured_content  # type: ignore[return-value]


async def main() -> None:
    out: list[str] = [
        "# Demo outputs",
        "",
        f"Generated by `scripts/demo.py` on {dt.date.today()} against the real stdio server "
        "(keyless) and the locally ingested corpus. Values are copied from tool results.",
        "",
    ]
    async with Client(SERVER) as client:
        # 1. MPC wording changes
        cmp = await call(client, "compare_ppk_statements", {"language": "en"})
        a, b = cmp["decision_a"], cmp["decision_b"]
        out += [
            f"## 1. Latest vs previous MPC decision ({a['doc_date']} → {b['doc_date']})",
            "",
            f"**Decision sentence ({b['doc_date']}):** {cmp['decision_sentence_b']}",
            "",
            f"Unchanged sentences: {cmp['unchanged_sentences']} · changes: {len(cmp['changes'])} · "
            f"members changed: {cmp['members_changed']} · heuristic tone: *{cmp['tone']['label']}* "
            f"(score {cmp['tone']['score']}, {cmp['tone']['method']})",
            "",
            "| Change | Text |",
            "|---|---|",
        ]
        for c in cmp["changes"]:
            text = c["text_b"] if c["kind"] != "removed" else c["text_a"]
            out.append(f"| {c['kind']} ({c['tone']}) | {text} |")
        out += ["", *[f"- {cite(c)}" for c in cmp["citations"]], ""]

        # 2. FX move with context
        ex = await call(
            client,
            "explain_move",
            {"series_code": "FX:USD", "start": "2026-06-01", "end": "2026-09-30"},
        )
        mv = ex["movement"]
        out += [
            "## 2. USD/TRY, June–September 2026, with document context",
            "",
            f"Frequency: {ex['frequency']} (last bulletin of each week). "
            f"{mv['first_date']}: **{mv['first_value']:.4f}** → {mv['last_date']}: **{mv['last_value']:.4f}** "
            f"({mv['change_pct']:+.2f}%). Range {mv['min_value']:.4f} ({mv['min_date']}) – "
            f"{mv['max_value']:.4f} ({mv['max_date']}).",
            "",
            "| Evidence | Date | Page | Relevance | Excerpt (truncated) |",
            "|---|---|---|---|---|",
        ]
        items = (
            [ex["decision_in_force_at_start"]] if ex["decision_in_force_at_start"] else []
        ) + ex["evidence"]
        for e in items:
            excerpt = e["untrusted_excerpt"][:160].replace("|", "/")
            out.append(
                f"| `{e['doc_id']}` | {e['doc_date']} | {e['page']} | {e['relevance']} | {excerpt}… |"
            )
        out += ["", f"> {ex['notes'][0]}", ""]

        # 3. Report question with page citations
        latest = (
            await call(client, "list_documents", {"doc_type": "ir", "language": "en", "limit": 1})
        )["documents"][0]
        grep = await call(
            client,
            "grep_documents",
            {
                "pattern": "inflation expectations",
                "doc_type": "ir",
                "language": "en",
                "date_from": latest["doc_date"],
                "max_results": 3,
                "context_chars": 220,
            },
        )
        out += [
            f"## 3. Where does the latest Inflation Report ({latest['doc_id']}) discuss inflation expectations?",
            "",
        ]
        for m in grep["matches"]:
            out.append(
                f"- PDF p. {m['page']} (printed {m['page_label']}): “…{strip(m['snippet']).strip()[:300]}…”"
            )
        out += ["", *[f"- {cite(c)}" for c in grep["citations"][:3]], ""]

        # 4. Month-end USD/TRY series (used for the README chart)
        series = await call(
            client,
            "get_series",
            {
                "series_code": "FX:USD:forex_buying",
                "start": "2026-01-01",
                "end": "2026-09-30",
                "frequency": "monthly",
            },
        )
        out += [
            "## 4. USD/TRY month-end (TCMB forex buying), 2026",
            "",
            "| Month (bulletin) | TRY per USD |",
            "|---|---|",
        ]
        out += [f"| {o['period']} | {o['value']:.4f} |" for o in series["observations"]]
        out += ["", f"Source: {cite(series['citations'][0])}", ""]

        # 5. EVDS (only with a key)
        sources = await call(client, "list_data_sources", {})
        if sources["keyless_mode"]:
            out += [
                "## 5. EVDS policy-rate lookup",
                "",
                "Skipped: no `EVDS_API_KEY` in this environment.",
                "",
            ]
        else:
            found = await call(client, "search_series", {"query": "policy rate one week repo"})
            out += [
                "## 5. EVDS search: policy rate",
                "",
                *[f"- `{h['series_code']}` {h['name_en'] or h['name']}" for h in found["hits"][:5]],
                "",
            ]
    print("\n".join(out))


if __name__ == "__main__":
    anyio.run(main)
